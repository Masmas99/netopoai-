"""
Cisco IOS CLI Configuration Generator for NetTopo AI.
Generates syntactically correct, copy-paste ready Cisco IOS configuration scripts
for Routers, Catalyst Switches, and Host network settings.
"""

from typing import Dict, List
from app.models.topology import DeviceConfig, Topology
from app.core.catalog import DeviceType


class CiscoConfigGenerator:
    def __init__(self, topology: Topology):
        self.topology = topology

    def generate_all_configs(self) -> Dict[str, str]:
        """
        Generates configuration scripts for all devices in the topology.
        Returns a dictionary mapping hostname -> configuration script text.
        """
        configs: Dict[str, str] = {}
        for dev in self.topology.devices:
            configs[dev.hostname] = self.generate_device_config(dev)
        return configs

    def generate_device_config(self, device: DeviceConfig) -> str:
        """
        Generates Cisco IOS commands or PC settings for a single device.
        """
        if device.device_type == DeviceType.ROUTER:
            return self._generate_router_config(device)
        elif device.device_type in (DeviceType.SWITCH, DeviceType.LAYER3_SWITCH):
            return self._generate_switch_config(device)
        elif device.device_type in (DeviceType.PC, DeviceType.LAPTOP, DeviceType.SERVER):
            return self._generate_host_config(device)
        else:
            return f"! Generic configuration for {device.hostname}\nhostname {device.hostname}\n"

    def _generate_router_config(self, dev: DeviceConfig) -> str:
        lines: List[str] = [
            f"! ==================================================",
            f"! Cisco IOS Configuration for Router: {dev.hostname}",
            f"! Model: {dev.model}",
            f"! Generated by NetTopo AI",
            f"! ==================================================",
            "enable",
            "configure terminal",
            f"hostname {dev.hostname}",
            "no ip domain-lookup",
            "",
        ]

        # Interfaces
        for iface in dev.interfaces:
            if iface.ip_address and iface.subnet_mask:
                lines.append(f"! Interface {iface.name}")
                lines.append(f"interface {iface.name}")
                lines.append(f" ip address {iface.ip_address} {iface.subnet_mask}")
                if iface.clock_rate:
                    lines.append(f" clock rate {iface.clock_rate}")
                if not iface.is_shutdown:
                    lines.append(" no shutdown")
                lines.append(" exit")
                lines.append("")

        # Static Routes
        if dev.static_routes:
            lines.append("! Static Routing Table")
            for route in dev.static_routes:
                target = route.next_hop or route.exit_interface or ""
                lines.append(f"ip route {route.destination_network} {route.subnet_mask} {target}".strip())
            lines.append("")

        # Custom commands
        if dev.custom_commands:
            lines.append("! Additional Configuration")
            for cmd in dev.custom_commands:
                lines.append(cmd)
            lines.append("")

        lines.extend([
            "end",
            "write memory",
            "",
            f"! End of configuration for {dev.hostname}",
        ])

        return "\n".join(lines)

    def _generate_switch_config(self, dev: DeviceConfig) -> str:
        lines: List[str] = [
            f"! ==================================================",
            f"! Cisco IOS Configuration for Switch: {dev.hostname}",
            f"! Model: {dev.model}",
            f"! Generated by NetTopo AI",
            f"! ==================================================",
            "enable",
            "configure terminal",
            f"hostname {dev.hostname}",
            "no ip domain-lookup",
            "",
        ]

        if dev.device_type == DeviceType.LAYER3_SWITCH:
            lines.append("! Enable Layer 3 Routing")
            lines.append("ip routing")
            lines.append("")

        # Group VLAN interfaces
        vlans_needed = set()
        for iface in dev.interfaces:
            if iface.vlan_id:
                vlans_needed.add(iface.vlan_id)

        if vlans_needed:
            lines.append("! VLAN Definitions")
            for vlan in sorted(vlans_needed):
                lines.append(f"vlan {vlan}")
                lines.append(f" name VLAN_{vlan}")
                lines.append(" exit")
            lines.append("")

        # Switchports
        for iface in dev.interfaces:
            lines.append(f"interface {iface.name}")
            if iface.is_trunk:
                lines.append(" switchport mode trunk")
            elif iface.vlan_id:
                lines.append(" switchport mode access")
                lines.append(f" switchport access vlan {iface.vlan_id}")
            if not iface.is_shutdown:
                lines.append(" no shutdown")
            lines.append(" exit")
            lines.append("")

        # Default Gateway for L2 Switch
        if dev.default_gateway and dev.device_type == DeviceType.SWITCH:
            lines.append(f"ip default-gateway {dev.default_gateway}")
            lines.append("")

        lines.extend([
            "end",
            "write memory",
            "",
            f"! End of configuration for {dev.hostname}",
        ])

        return "\n".join(lines)

    def _generate_host_config(self, dev: DeviceConfig) -> str:
        lines: List[str] = [
            f"# ==================================================",
            f"# Host Network Configuration: {dev.hostname}",
            f"# Type: {dev.device_type.value.upper()}",
            f"# Open Packet Tracer -> Click {dev.hostname} -> Desktop -> IP Configuration",
            f"# ==================================================",
        ]

        for iface in dev.interfaces:
            lines.append(f"Interface:       {iface.name}")
            lines.append(f"IP Address:      {iface.ip_address or 'DHCP / Not configured'}")
            lines.append(f"Subnet Mask:     {iface.subnet_mask or '255.255.255.0'}")
            lines.append(f"Default Gateway: {dev.default_gateway or 'None'}")
            lines.append(f"DNS Server:      {dev.dns_server or 'None'}")
            lines.append("")

        return "\n".join(lines)

